// Reverse map for EN to PT translations
const en_to_pt = {};
for (const [pt, en] of Object.entries(pt_to_en)) {
    en_to_pt[en] = pt;
}

// Utility to normalize white spaces (replacing any newlines or multiple spaces with a single space)
function normalizeText(str) {
    if (!str) return '';
    return str.replace(/\s+/g, ' ').trim();
}

// Function to translate the page DOM elements
function translatePage(targetLang) {
    const map = targetLang === 'en' ? pt_to_en : en_to_pt;

    function getTranslation(text) {
        const cleanText = normalizeText(text);
        let lookupText = cleanText;
        let suffix = '';
        if (cleanText.endsWith(':')) {
            lookupText = cleanText.slice(0, -1).trim();
            suffix = ':';
        }
        
        if (map[lookupText]) {
            return map[lookupText] + suffix;
        }
        return null;
    }

    function walk(node) {
        if (node.nodeType === Node.TEXT_NODE) {
            const translation = getTranslation(node.nodeValue);
            if (translation !== null) {
                const leading = node.nodeValue.match(/^\s*/)[0];
                const trailing = node.nodeValue.match(/\s*$/)[0];
                node.nodeValue = leading + translation + trailing;
            }
        } else if (node.nodeType === Node.ELEMENT_NODE) {
            if (node.tagName !== 'SCRIPT' && node.tagName !== 'STYLE' && node.tagName !== 'TEXTAREA') {
                // Translate placeholder
                if (node.hasAttribute('placeholder')) {
                    const translation = getTranslation(node.getAttribute('placeholder'));
                    if (translation !== null) {
                        node.setAttribute('placeholder', translation);
                    }
                }
                // Translate title attribute
                if (node.hasAttribute('title')) {
                    const translation = getTranslation(node.getAttribute('title'));
                    if (translation !== null) {
                        node.setAttribute('title', translation);
                    }
                }
                
                // Recurse children
                for (let child = node.firstChild; child; child = child.nextSibling) {
                    walk(child);
                }
            }
        }
    }

    walk(document.body);

    // Document Title Translation
    const docTitle = document.title;
    if (targetLang === 'en') {
        if (docTitle.includes("Linha de Apoio ao Caloiro")) {
            document.title = docTitle.replace("Linha de Apoio ao Caloiro", "Freshman Support Line");
        }
        if (docTitle.includes("Espaço de Núcleos")) {
            document.title = docTitle.replace("Espaço de Núcleos", "Student Hubs Space");
        }
        if (docTitle.includes("Desafios Fotográficos")) {
            document.title = docTitle.replace("Desafios Fotográficos", "Photo Challenges");
        }
        if (docTitle.includes("Rede Social")) {
            document.title = docTitle.replace("Rede Social", "Social Network");
        }
    } else {
        if (docTitle.includes("Freshman Support Line")) {
            document.title = docTitle.replace("Freshman Support Line", "Linha de Apoio ao Caloiro");
        }
        if (docTitle.includes("Student Hubs Space")) {
            document.title = docTitle.replace("Student Hubs Space", "Espaço de Núcleos");
        }
        if (docTitle.includes("Photo Challenges")) {
            document.title = docTitle.replace("Photo Challenges", "Desafios Fotográficos");
        }
        if (docTitle.includes("Social Network")) {
            document.title = docTitle.replace("Social Network", "Rede Social");
        }
    }
}

// Toggle language state
function toggleLanguage() {
    const currentLang = localStorage.getItem('laac_lang') || 'pt';
    const newLang = currentLang === 'pt' ? 'en' : 'pt';
    localStorage.setItem('laac_lang', newLang);
    window.location.reload();
}

// Inject Language Switcher Button dynamically into navigation bar
function injectLanguageBtn() {
    if (document.getElementById('lang-btn')) return;

    const currentLang = localStorage.getItem('laac_lang') || 'pt';
    
    // Create button matching navbar theme styling
    const btn = document.createElement('button');
    btn.className = 'nav-btn lang-btn';
    btn.id = 'lang-btn';
    btn.style.fontSize = '0.85rem';
    btn.style.fontWeight = '700';
    btn.style.display = 'inline-flex';
    btn.style.alignItems = 'center';
    btn.style.justifyContent = 'center';
    btn.style.gap = '5px';
    btn.title = 'Switch Language / Alterar Idioma';
    btn.innerHTML = `<i class="fa-solid fa-globe"></i> <span>${currentLang.toUpperCase()}</span>`;
    btn.onclick = toggleLanguage;

    // In a sidebar layout (e.g. admin.html)
    const sidebar = document.querySelector('.sidebar nav');
    if (sidebar) {
        btn.className = 'sidebar-link';
        btn.style.marginTop = 'auto';
        btn.style.border = '1px solid var(--glass-border)';
        btn.style.background = 'var(--glass)';
        btn.style.padding = '0.8rem 1.2rem';
        btn.style.borderRadius = '12px';
        btn.style.cursor = 'pointer';
        sidebar.appendChild(btn);
        return;
    }

    // In normal navbar layouts
    const userAction = document.querySelector('.user-action');
    if (userAction) {
        userAction.style.display = 'flex';
        userAction.style.alignItems = 'center';
        userAction.style.gap = '10px';
        userAction.insertBefore(btn, userAction.firstChild);
    } else {
        const navLinks = document.querySelector('.nav-links');
        if (navLinks) {
            if (navLinks.tagName === 'UL') {
                const li = document.createElement('li');
                li.appendChild(btn);
                navLinks.appendChild(li);
            } else {
                navLinks.appendChild(btn);
            }
        } else {
            const navbar = document.querySelector('.navbar');
            if (navbar) {
                const container = navbar.querySelector('.nav-content') || navbar;
                container.appendChild(btn);
            }
        }
    }
}

// MutationObserver to translate dynamically loaded components automatically
let langObserver = null;
function startTranslationObserver() {
    if (langObserver) langObserver.disconnect();
    
    const currentLang = localStorage.getItem('laac_lang') || 'pt';
    if (currentLang === 'pt') return; // PT is default language, observer not required

    langObserver = new MutationObserver((mutations) => {
        langObserver.disconnect();
        translatePage(currentLang);
        startTranslationObserver();
    });

    langObserver.observe(document.body, {
        childList: true,
        subtree: true
    });
}

// Initialize on DOM ready
document.addEventListener('DOMContentLoaded', () => {
    injectLanguageBtn();
    const currentLang = localStorage.getItem('laac_lang') || 'pt';
    if (currentLang === 'en') {
        translatePage('en');
        startTranslationObserver();
    }
});
